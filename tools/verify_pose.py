#!/usr/bin/env python3
"""Verify recorded retail EE/VU rest poses against native output.

Requires manifests generated by the documented pose-corpus commands. Hashes bind
those original source files, output matrices, binaries, and the pinned Play core.
This checks rest poses in initial scale mode; animation and rendering are separate.
"""
import json
import math
import struct
import subprocess
from pathlib import Path
from inspect_disc import sha256
from prepare_assets import ELF_HASH

ABS_TOLERANCE = 2e-5
REL_TOLERANCE = 2e-6

def floats(path):
    data = Path(path).read_bytes()
    if len(data) % 4:
        raise ValueError('Invalid float buffer')
    return struct.unpack('<' + str(len(data)//4) + 'f', data)

def main():
    if sha256(Path('local/extracted/SCUS_971.29')) != ELF_HASH:
        raise ValueError('Wrong original ELF')
    original_manifest = Path('local/retail-poses.tsv')
    native_manifest = Path('local/native-poses.tsv')
    original = [line.split('\t') for line in original_manifest.read_text().splitlines()]
    native = [line.split('\t') for line in native_manifest.read_text().splitlines()]
    files = sorted(str(p) for p in Path('local/xpf-decoded').rglob('*.xmd'))
    if not files or [r[0] for r in original] != files or [r[0] for r in native] != files:
        raise ValueError('Manifest coverage differs from the exact model corpus')
    matrices = values = equal = 0
    worst = {'absolute_error': 0.0}
    results = []
    for (source, source_hash, a, count), (_, b, native_count) in zip(original, native):
        if sha256(Path(source)) != source_hash or count != native_count:
            raise ValueError('Source hash or matrix count mismatch')
        x, y = floats(a), floats(b)
        if len(x) != int(count)*16 or len(x) != len(y):
            raise ValueError('Pose buffer size mismatch')
        max_error = 0.0
        for index, (expected, actual) in enumerate(zip(x, y)):
            if not math.isfinite(expected) or not math.isfinite(actual):
                raise ValueError(f'Non-finite pose: {source}, component {index}')
            error = abs(expected-actual)
            if error > ABS_TOLERANCE + REL_TOLERANCE*abs(expected):
                raise ValueError(f'Pose mismatch: {source}, component {index}: {expected} != {actual}')
            if error > worst['absolute_error']:
                worst = {'absolute_error': error, 'path': source, 'component': index,
                         'retail': expected, 'native': actual}
            max_error = max(max_error, error)
            equal += expected == actual
        matrices += int(count)
        values += len(x)
        results.append({'source': source, 'source_sha256': source_hash, 'matrices': int(count),
                        'retail_pose_sha256': sha256(Path(a)), 'native_pose_sha256': sha256(Path(b)),
                        'maximum_absolute_error': max_error})
    original_sine, native_sine = floats('local/retail-sine.f32'), floats('local/native-sine.f32')
    if len(original_sine) != 16384 or len(native_sine) != 16384:
        raise ValueError('Sine table extent mismatch')
    sine_error = max(abs(a-b) for a, b in zip(original_sine, native_sine))
    if not all(math.isfinite(v) for v in original_sine+native_sine) or sine_error > 2e-7:
        raise ValueError('Native sine table exceeds tolerance')
    play_commit = subprocess.check_output(['git', '-C', 'references/Play', 'rev-parse', 'HEAD'], text=True).strip()
    report = {'elf_sha256': ELF_HASH, 'play_commit': play_commit,
              'oracle_binary_sha256': sha256(Path('build/play-research/okage-oracle/okage-pose-oracle')),
              'native_binary_sha256': sha256(Path('build/native/okage-assets')),
              'retail_manifest_sha256': sha256(original_manifest), 'native_manifest_sha256': sha256(native_manifest),
              'file_count': len(files), 'matrix_count': matrices, 'float_components': values,
              'numerically_equal_components': equal, 'absolute_tolerance': ABS_TOLERANCE,
              'relative_tolerance': REL_TOLERANCE, 'worst_component': worst,
              'sine_maximum_absolute_error': sine_error,
              'limits': __doc__.strip(), 'results': results}
    Path('local/pose-verification.json').write_text(json.dumps(report, indent=2)+'\n')
    summary = {k: v for k, v in report.items() if k != 'results'}
    summary['full_report_sha256'] = sha256(Path('local/pose-verification.json'))
    Path('docs/pose-validation.json').write_text(json.dumps(summary, indent=2)+'\n')
    print(f'PASS: {len(files)} files, {matrices} matrices, {values} components; max absolute error {worst["absolute_error"]:.9g}')

if __name__ == '__main__':
    main()
